# ============================================================
# سيناريو التكامل المشترك بين محرك مرنان ولغة البيان
# Mirnan & Bayan Integration Demo Script
# ============================================================

println("==========================================================")
println("     بدء سيناريو التكامل المشترك: مِرنان V8 ↔ لغة البيان      ")
println("==========================================================")

# 1. إعداد مسارات التحميل لجوليا
using Pkg; Pkg.activate(@__DIR__)
push!(LOAD_PATH, joinpath(@__DIR__, "BayanLanguage"))

include(joinpath(@__DIR__, "src", "MirnanNew.jl")); using .MirnanNew
using compiler
include("BayanLanguage/tools/bayan_compiler_tool.jl")

using .BayanCompilerToolModule

# تهيئة أداة المترجم للبيان
tool = BayanCompilerTool()

# 2. كتابة كود بلغة البيان يدمج المحركين
bayan_code = """
# ------------------------------------------------------------
# القسم الأول: العمليات الموجية الإجرائية في البيان
# ------------------------------------------------------------
اطبع("--- القسم الأول: العمليات الموجية في البيان ---")

م١ = موجة("العلم")
م٢ = موجة("النور")
م_تداخل = تداخل(م١, م٢)

اطبع("تردد موجة العلم: " * string(م١.frequency))
اطبع("تردد موجة النور: " * string(م٢.frequency))
اطبع("حزمة التداخل الناتجة: " * م_تداخل.text)
اطبع("تردد حزمة التداخل: " * string(م_تداخل.frequency))
اطبع("كتلة حزمة التداخل: " * string(م_تداخل.mass))

# اقتران طوري وقياس
م_اقتران = اقتران(م١, م٢)
م_قياس = قياس(م_اقتران, م١)
اطبع("القياس الهولوغرافي لاسترجاع المتجه: " * م_قياس.text)

# ------------------------------------------------------------
# القسم الثاني: الاستدلال المنطقي الرنيني الهجين بـ مِرنان
# ------------------------------------------------------------
اطبع("")
اطبع("--- القسم الثاني: الاستدلال المنطقي الهجين بـ مِرنان ---")

هجين {
    # تسجيل حقائق فيزيائية دلالية
    حقيقة علم("نور").
    حقيقة علم("معرفة").
    حقيقة انسان("سقراط").
    
    # قواعد استدلال عامة
    قاعدة فضيلة(?س) :- علم(?س).
    قاعدة حكيم(?س) :- انسان(?س).
    
    # ١. استعلام متطابق حرفياً (طاقة رنين كاملة = 1.0)
    اطبع("1. استفسار متطابق حرفياً: هل العلم نور؟")
    استفسار علم("نور").
    
    # ٢. استعلام رنيني لمتغيرات إملائية وصرفية (نور ↔ نوره)
    اطبع("2. استفسار رنيني صرفي (نور ↔ نوره):")
    استفسار علم("نوره").
    
    # ٣. استعلام رنيني لقواعد الاستنباط (فضيلة ↔ معرفه)
    اطبع("3. استفسار رنيني عبر قواعد فضيلة (معرفة ↔ معرفه):")
    استفسار فضيلة("معرفه").
    
    # ٤. استعلام رنيني لأسماء العلم (سقراط ↔ سقراطه)
    اطبع("4. استفسار رنيني لأسماء العلم (سقراط ↔ سقراطه):")
    استفسار حكيم("سقراطه").
    
    # ٥. استعلام متباعد طورياً تماماً (سقراط ↔ افلاطون)
    اطبع("5. استفسار متباعد طورياً (سقراط ↔ افلاطون):")
    استفسار حكيم("افلاطون").
}
"""

println("⟳ جاري ترجمة كود البيان إلى جوليا وتشغيله ديناميكياً...")
flush(stdout)

result = run_bayan_code(tool, bayan_code, inline=false)

println()
println("==========================================================")
println("                   مخرجات التشغيل الفعلي                   ")
println("==========================================================")
if occursin("[BAYAN EXECUTION SUCCESS]", result)
    output = replace(result, "[BAYAN EXECUTION SUCCESS]\n" => "")
    println(output)
else
    println(result)
end
println("==========================================================")
println("✓ تم انتهاء السيناريو والتكامل بنجاح تام!")
println("==========================================================")
