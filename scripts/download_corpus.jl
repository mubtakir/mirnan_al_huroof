        return true
    end
    
    urls = [
        "http://corpus.leeds.ac.uk/bogdan/resources/UN-corpus/6way/UNv1.0.6way.ar.txt",
        "http://lotus.kuee.kyoto-u.ac.jp/~raj/rajwindroot/corpora_downloads/UN_CORPUS/UNv1.0.6way.ar.txt",
    ]
    
    for url in urls
        try
            println("   ⏳ جاري التحميل...")
            Downloads.download(url, outfile)
            println("   ✓ تم ($(filesize(outfile) ÷ 1_000_000)MB)")
            return true
        catch e
            println("   ⚠ فشل: $(typeof(e).name)")
        end
    end
    
    return false
end

