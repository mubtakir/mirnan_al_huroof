function merge_all()
    println("🔗 دمج كل الكوربسات...")
    
    total_size = 0
    all_files = String[]
    
    for dir in [CORPUS_DIR, DOWNLOAD_DIR]
        isdir(dir) || continue
        for file in readdir(dir)
            if endswith(file, ".txt")
                filepath = joinpath(dir, file)
                size = filesize(filepath)
                if size > 1000
                    push!(all_files, filepath)
                    total_size += size
                    println("   ✓ $file ($(size ÷ 1000)KB)")
                end
            end
        end
    end
    
    # دمج
    merged_file = joinpath(CORPUS_DIR, "arabic_corpus_merged.txt")
    open(merged_file, "w") do io
        for filepath in all_files
            content = read(filepath, String)
            write(io, content, "\n\n")
        end
    end
    
    total_words = 0
    for filepath in all_files
        content = read(filepath, String)
        total_words += length(split(content))
    end
    
    println()
    println("   📊 الإجمالي:")
    println("   ✓ $(length(all_files)) ملف")
    println("   ✓ $total_words كلمة")
    println("   ✓ $(total_size ÷ 1_000_000)MB حجم")
    println("   ✓ $merged_file")
    
    return length(all_files)
end

