# 1. Hindawi Arabic Books من HuggingFace
# ═══════════════════════════════════════════════════════
function download_hindawi()
    println("📚 تحميل Hindawi Arabic Books (81.5M كلمة)...")
    
    outfile = joinpath(DOWNLOAD_DIR, "hindawi_books.txt")
    if isfile(outfile) && filesize(outfile) > 1_000_000
        println("   ⏭ موجود ($(filesize(outfile) ÷ 1_000_000)MB)")
        return true
    end
    
    # HuggingFace API — تحميل dataset مُحَمَّل مسبقاً
    # نستخدم parquet files مباشرة
    base_url = "https://huggingface.co/datasets/mohres/The_Arabic_E-Book_Corpus/resolve/main/data"
    
    downloaded = 0
    for shard in 0:4  # أول 5 shards = ~1750 كتاب
        try
            url = "$base_url/train-$shard.parquet"
            tmp = joinpath(DOWNLOAD_DIR, "hindawi_shard_$shard.parquet")
            
            if !isfile(tmp)
                println("   ⏳ جاري تحميل shard $shard...")
                Downloads.download(url, tmp)
            end
            
            downloaded += 1
            println("   ✓ shard $shard ($(filesize(tmp) ÷ 1_000_000)MB)")
            
        catch e
            println("   ⚠ فشل shard $shard: $e")
        end
        sleep(1)
    end
    
    if downloaded > 0
        # استخراج النصوص من parquet (باستخدام python)
        println("   ⏳ استخراج النصوص...")
        try
            cmd = `python3 -c "
import pandas as pd
import os

files = [f'downloads/hindawi_shard_{i}.parquet' for i in range($downloaded)]
dfs = []
for f in files:
    if os.path.exists(f):
        dfs.append(pd.read_parquet(f))

if dfs:
    df = pd.concat(dfs)
    texts = df['text'].dropna().tolist()
    with open('$outfile', 'w', encoding='utf-8') as out:
        for t in texts:
            if isinstance(t, str) and len(t) > 50:
                out.write(t + '\n\n')
    print(f'Extracted {len(texts)} books')
"`
            run(cmd)
        catch
            println("   ⚠ فشل الاستخراج — جرّب يدوياً")
        end
    end
    
    return downloaded > 0
end

