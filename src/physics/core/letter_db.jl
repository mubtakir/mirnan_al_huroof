"""
    get_letter_params(letter::Char) -> Union{Vector, Nothing}
"""
function get_letter_params(letter::Char)
    return get(LETTER_DB, letter, nothing)
end

"""
    list_letters() -> Vector{Char}
"""
function list_letters()
    return collect(keys(LETTER_DB))
end

"""
    letter_term_count(letter::Char) -> Int
"""
function letter_term_count(letter::Char)
    params = get_letter_params(letter)
    return params === nothing ? 0 : length(params)
end

"""
    total_params(letter::Char) -> Int
"""
function total_params(letter::Char)
    return letter_term_count(letter) * TERM_DIM
end

